ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'output' / 'documents'
OUT.mkdir(parents=True, exist_ok=True)

def source_table(filename, header):
    text = (ROOT / 'docs' / filename).read_text(encoding='utf-8')
    lines = text[text.index(header):].splitlines()
    result = []
    for line in lines[2:]:
        if not line.startswith('|'):
            break
        result.append([c.strip().replace('`', '') for c in line.strip('|').split('|')])
    return result

C6 = source_table('SOIL_NODE_ESP32C6_PINOUT_RU.md', '| GPIO |')
S3 = source_table('UNIVERSAL_12V_ESP32S3_PINOUT_RU.md', '| GPIO |')
EXP = source_table('UNIVERSAL_12V_ESP32S3_PINOUT_RU.md', '| Порт |')
assert len(C6) == 22 and len(S3) == 36 and len(EXP) == 24

class Spec:
    def __init__(self, stem, title, subtitle):
        self.stem = stem
        self.doc = Document()
        self.md = [f'# {title}', '', subtitle, '']
        s = self.doc.sections[0]
        s.page_width, s.page_height = Inches(8.5), Inches(11)
        s.top_margin = s.bottom_margin = Inches(.57)
        s.left_margin = s.right_margin = Inches(.60)
        s.footer_distance = Inches(.23)
        for name in ['Normal', 'Title', 'Subtitle', 'Heading 1', 'Heading 2']:
            st = self.doc.styles[name]
            st.font.name = 'Arial'
            st.font.color.rgb = RGBColor(0, 0, 0)
            st.paragraph_format.space_after = Pt(5)
        normal = self.doc.styles['Normal']
        normal.font.size = Pt(10.5)
        normal.paragraph_format.line_spacing = 1.05
        self.doc.styles['Title'].font.size = Pt(20)
        self.doc.styles['Subtitle'].font.size = Pt(10)
        for name, size in [('Heading 1', 14), ('Heading 2', 11)]:
            self.doc.styles[name].font.size = Pt(size)
            self.doc.styles[name].font.bold = True
            self.doc.styles[name].paragraph_format.space_before = Pt(9)
        self.doc.add_paragraph(title, 'Title')
        self.doc.add_paragraph(subtitle, 'Subtitle')
        foot = s.footer.paragraphs[0]
        foot.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        run = foot.add_run('Версия 1.0  |  ')
        run.font.size = Pt(8)
        field = OxmlElement('w:fldSimple')
        field.set(qn('w:instr'), 'PAGE')
        foot._p.append(field)
        self.doc.core_properties.title = title
        self.doc.core_properties.subject = 'Техническое задание на разработку печатной платы'
        self.doc.core_properties.author = 'AmudarIO'
        self.doc.core_properties.keywords = 'PCB, техническое задание, версия 1.0'
    def h(self, text):
        self.doc.add_paragraph(text, 'Heading 1')
        self.md += ['## ' + text, '']
    def p(self, text):
        self.doc.add_paragraph(text)
        self.md += [text, '']
    def bullets(self, *items):
        for text in items:
            p = self.doc.add_paragraph()
            p.paragraph_format.left_indent = Pt(10)
            p.paragraph_format.first_line_indent = Pt(-10)
            p.add_run('• ' + text)
            self.md += ['- ' + text]
        self.md += ['']
    def page(self):
        self.doc.add_page_break()
    def table(self, headers, rows, widths, size=9.5):
        t = self.doc.add_table(rows=1, cols=len(headers))
        t.autofit = False
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for col, width in zip(t.columns, widths):
            col.width = Inches(width)
        for i, vals in enumerate([headers] + rows):
            row = t.rows[0] if i == 0 else t.add_row()
            for cell, value, width in zip(row.cells, vals, widths):
                cell.width = Inches(width)
                cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
                tcpr = cell._tc.get_or_add_tcPr()
                marg = OxmlElement('w:tcMar')
                for edge, v in [('top', 45), ('bottom', 45), ('left', 70), ('right', 70)]:
                    el = OxmlElement('w:' + edge); el.set(qn('w:w'), str(v)); el.set(qn('w:type'), 'dxa'); marg.append(el)
                tcpr.append(marg)
                shading = OxmlElement('w:shd')
                shading.set(qn('w:fill'), 'DCE6F1' if i == 0 else ('F4F6F8' if i % 2 == 0 else 'FFFFFF'))
                tcpr.append(shading)
                p = cell.paragraphs[0]
                p.paragraph_format.space_after = Pt(0)
                p.paragraph_format.space_before = Pt(0)
                p.paragraph_format.line_spacing = 1.0
                if width <= .8 or str(value).isdigit():
                    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                r = p.add_run(str(value)); r.font.name = 'Arial'; r.font.size = Pt(size); r.bold = i == 0
            trpr = row._tr.get_or_add_trPr()
            trpr.append(OxmlElement('w:cantSplit'))
            if i == 0:
                trpr.append(OxmlElement('w:tblHeader'))
        borders = OxmlElement('w:tblBorders')
        for edge in ['top','left','bottom','right','insideH','insideV']:
            el = OxmlElement('w:' + edge); el.set(qn('w:val'), 'single'); el.set(qn('w:sz'), '4'); el.set(qn('w:color'), 'D9D9D9'); borders.append(el)
        t._tbl.tblPr.append(borders)
        self.doc.add_paragraph().paragraph_format.space_after = Pt(0)
        self.md += ['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join(['---'] * len(headers)) + ' |']
        self.md += ['| ' + ' | '.join(map(str, r)) + ' |' for r in rows] + ['']
    def save(self):
        target = OUT / (self.stem + '.docx')
        # Word's template can carry a theme-colored Title border.
        for part in [self.doc._element, self.doc.styles.element]:
            for border in list(part.iter(qn('w:pBdr'))):
                border.getparent().remove(border)
        self.doc.save(target)
        (ROOT / 'docs' / (self.stem + '.md')).write_text('\n'.join(self.md), encoding='utf-8')
        print(target)

